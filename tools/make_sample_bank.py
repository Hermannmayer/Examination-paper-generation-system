def build_rows():
    rows = []

    def difficulty_at(index):
        return DIFFICULTY_CYCLE[index % len(DIFFICULTY_CYCLE)]

    def knowledge_at(index):
        return KNOWLEDGE_AREAS[index % len(KNOWLEDGE_AREAS)]

    for index, (stem, answer) in enumerate(JUDGMENT):
        rows.append(["判断题", stem, answer, difficulty_at(index),
                     knowledge_at(index), None, None, None, None])

    for index, (stem, options, answer) in enumerate(MCQ):
        slot = index + len(JUDGMENT)
        rows.append(["单选题", stem, answer, difficulty_at(slot),
                     knowledge_at(slot), *options])

    for index, (stem, options, answer) in enumerate(MCQ_MULTI):
        slot = index + len(JUDGMENT) + len(MCQ)
        rows.append(["多选题", stem, answer, difficulty_at(slot),
                     knowledge_at(slot), *options])

    for index, (stem, answer) in enumerate(SHORT_ANSWER):
        slot = index + len(JUDGMENT) + len(MCQ) + len(MCQ_MULTI)
        rows.append(["简答题", stem, answer, difficulty_at(slot),
                     knowledge_at(slot), None, None, None, None])

    return rows


def main():
    rows = build_rows()

    workbook = openpyxl.Workbook()
    sheet = workbook.active
    sheet.title = "题库"
    sheet.append(HEADERS)
    for row in rows:
        sheet.append(row)

    for column, width in {"A": 10, "B": 52, "C": 10, "D": 8, "E": 22}.items():
        sheet.column_dimensions[column].width = width
    for column in ("F", "G", "H", "I"):
        sheet.column_dimensions[column].width = 16

    sheet.freeze_panes = "A2"
    workbook.save(OUTPUT)

    counts = {}
    for row in rows:
        counts[row[0]] = counts.get(row[0], 0) + 1
    difficulties = {}
    for row in rows:
        difficulties[row[3]] = difficulties.get(row[3], 0) + 1

    print(f"已生成 {OUTPUT}")
    print(f"  共 {len(rows)} 题　{counts}")
    print(f"  难度分布　{difficulties}")
    print(f"  知识点　　{len(KNOWLEDGE_AREAS)} 个章节")
    print(f"  列：{'、'.join(HEADERS)}")


if __name__ == "__main__":
    main()
